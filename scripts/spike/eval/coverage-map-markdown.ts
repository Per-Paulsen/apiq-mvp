/**
 * Renders coverage.json into committed COVERAGE.md.
 * Pure function — no fs / no env-deps; testable with synthetic input.
 */

import type { CoverageJson } from './coverage-map-aggregator.js';

function shortSha(sha: string): string {
  if (!sha || sha === 'unknown' || sha === 'uncommitted') return sha;
  return sha.slice(0, 12);
}

function fmtMin(ms: number): string {
  return (ms / 1000 / 60).toFixed(2) + 'min';
}

function fmtSec(ms: number): string {
  return (ms / 1000).toFixed(1) + 's';
}

function escapePipes(s: string): string {
  // Markdown-table cell: escape | and replace newlines with spaces.
  return s.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}

export function renderCoverageMarkdown(c: CoverageJson): string {
  const lines: string[] = [];

  // ---- Header banner ----
  lines.push('# COVERAGE.md — Empirical fire-data per detector / pattern / lens');
  lines.push('');
  lines.push(
    '> **Auto-generated by `npm run build-coverage` (Welle I / I2). Do not edit manually.**'
  );
  lines.push('');
  lines.push(`- **Last regenerated:** \`${c.generated_at}\``);
  lines.push(`- **Total runtime:** \`${fmtMin(c.total_runtime_ms)}\``);
  lines.push(
    `- **Reference-spec git-SHAs:** ` +
      Object.entries(c.reference_spec_versions)
        .map(([spec, sha]) => `\`${spec}\`:\`${shortSha(sha)}\``)
        .join(', ')
  );
  lines.push(
    `- **Specs run:** ${c.per_spec.length} | ` +
      `**Unique detectors fired:** ${c.per_detector.length} | ` +
      `**Pattern-IDs covered:** ${c.per_pattern_id.length} | ` +
      `**Untested detectors:** ${c.untested_detectors.length}`
  );
  lines.push('');
  lines.push(
    '> Re-generate after any change to `scripts/spike/deterministic/` ' +
      'subtree. JSON-source: `coverage.json` (gitignored).'
  );
  lines.push('');

  // ---- Per-spec summary ----
  lines.push('## Per-spec summary');
  lines.push('');
  lines.push('| Spec | Total findings | Layer breakdown | Top-3 detectors | Runtime |');
  lines.push('|---|---:|---|---|---:|');
  for (const s of c.per_spec) {
    const layerBreak = Object.entries(s.per_layer_breakdown)
      .filter(([, n]) => n > 0)
      .map(([k, n]) => `${k}:${n}`)
      .join('<br>');
    const top3 = s.top_10_detectors_by_count
      .slice(0, 3)
      .map((d) => `\`${escapePipes(d.detector_id)}\` (${d.count})`)
      .join('<br>');
    lines.push(
      `| \`${s.spec_name}\` | ${s.total_findings} | ${layerBreak || '—'} | ${top3 || '—'} | ${fmtSec(s.runtime_ms)} |`
    );
  }
  lines.push('');

  // ---- Per-Lens table ----
  lines.push('## Per-Lens (yaml-rule lens-tag aggregation)');
  lines.push('');
  lines.push(
    '_Lens-totals derived from `apiq-meta.lenses` on yaml-rules. ' +
      'Module-class layer not yet tagged with lenses (I3 cross-ref-territory)._'
  );
  lines.push('');
  lines.push('| Lens | Pattern-IDs | Yaml-Rules-Active | Modules-Active | Fires-on |');
  lines.push('|---|---:|---:|---:|---|');
  for (const l of c.per_lens) {
    const fires = l.fires_on_specs_aggregate.length
      ? l.fires_on_specs_aggregate.map((s) => `\`${s}\``).join(', ')
      : '_(none)_';
    lines.push(
      `| \`${l.lens}\` | ${l.total_pattern_ids} | ${l.total_yaml_rules_active} | ${l.total_modules_active} | ${fires} |`
    );
  }
  lines.push('');

  // ---- Per-Pattern-ID table ----
  lines.push('## Per-Pattern-ID (only patterns with ≥1 fired detector)');
  lines.push('');
  lines.push(
    '_Pattern-IDs without any fired-detector are "substrate-only" candidates ' +
      '(drift-class-1; surfaced by I3)._'
  );
  lines.push('');
  lines.push('| Pattern-ID | Detector-IDs | Fires-on-specs |');
  lines.push('|---|---|---|');
  for (const p of c.per_pattern_id) {
    if (p.fires_on_specs.length === 0) continue;
    const detectors = p.detector_ids.map((d) => `\`${escapePipes(d)}\``).join('<br>');
    const fires = p.fires_on_specs.map((s) => `\`${s}\``).join(', ');
    lines.push(`| \`${p.pattern_id}\` | ${detectors} | ${fires} |`);
  }
  lines.push('');

  // ---- Per-detector full table (collapsible-style: include only fired) ----
  lines.push('## Per-detector (sorted by total-findings, fired-only)');
  lines.push('');
  lines.push(
    `_${c.per_detector.filter((d) => d.fires_on_specs.length > 0).length} ` +
      `fired detectors — the remaining ${c.per_detector.length - c.per_detector.filter((d) => d.fires_on_specs.length > 0).length} ` +
      'fired-on-zero-specs entries are listed in the "Untested detectors" section below._'
  );
  lines.push('');
  lines.push('| Detector-ID | Layer | Total | Per-Spec | Fires-on |');
  lines.push('|---|---|---:|---|---|');
  for (const d of c.per_detector) {
    if (d.fires_on_specs.length === 0) continue;
    const perSpecCells = Object.entries(d.finding_count_per_spec)
      .filter(([, n]) => n > 0)
      .map(([s, n]) => `${s}:${n}`)
      .join('<br>');
    lines.push(
      `| \`${escapePipes(d.detector_id)}\` | \`${d.layer}\` | ${d.total_findings_count} | ${perSpecCells || '—'} | ${d.fires_on_specs.length}/${c.per_spec.length} |`
    );
  }
  lines.push('');

  // ---- Untested-detectors ----
  lines.push('## Untested detectors (drift-class-2 candidates — dead-code-suspicion)');
  lines.push('');
  if (c.untested_detectors.length === 0) {
    lines.push('_(none — every detector that the pipeline emitted fired on ≥1 spec)_');
  } else {
    lines.push(
      `_${c.untested_detectors.length} detectors fired on 0 of ${c.per_spec.length} reference-specs. ` +
        'I3 will cross-reference against inventory.json to distinguish ' +
        '"missing-fixture" from "broken-detection".\\_'
    );
    lines.push('');
    for (const id of c.untested_detectors) {
      lines.push(`- \`${id}\``);
    }
  }
  lines.push('');

  return lines.join('\n');
}
